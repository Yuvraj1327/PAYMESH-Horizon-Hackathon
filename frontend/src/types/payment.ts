import type { DataOrigin, PaymentAsset } from "@/types/agent";

/** Backend `PaymentStatus` enum, verbatim. */
export type PaymentStatus =
  | "DRAFT" | "VALIDATED" | "AWAITING_SIGNATURE" | "SIGNED" | "SUBMITTED" | "PENDING"
  | "SETTLED" | "FAILED" | "EXPIRED" | "CANCELLED";

export const TERMINAL_STATUSES: readonly PaymentStatus[] = ["SETTLED", "FAILED", "EXPIRED", "CANCELLED"];
export const isTerminal = (s: PaymentStatus) => TERMINAL_STATUSES.includes(s);
/** Statuses where an HSP order may exist and the backend is still working: poll these. */
export const POLLING_STATUSES: readonly PaymentStatus[] = ["AWAITING_SIGNATURE", "SIGNED", "SUBMITTED", "PENDING"];

export type PaymentFilter = "all" | "pending" | "awaiting_authorization" | "processing" | "completed" | "failed" | "expired" | "cancelled";

export interface PaymentRecord {
  id: string;
  requestId: string;
  quotationId: string;
  providerAgentId: string;
  providerName: string;
  amount: string;
  asset: string;
  chainId: number;
  /** Null only for demo records: demo agents have no payout wallet. */
  recipient: string | null;
  status: PaymentStatus;
  failureReason: string | null;
  expiresAt: string;
  snapshotHash: string | null;
  createdAt: string;
  updatedAt: string;
  /** Present only when the backend/receipt provides one. Never generated by the UI. */
  txHash: string | null;
  source: DataOrigin;
}

export interface HspProgress {
  orderState: string;
  gatewayStatus: string | null;
  paymentRequestId: string | null;
  flowId: string | null;
  txHash: string | null;
  payerAddress: string | null;
  cartExpiry: string | null;
  lastPolledAt: string | null;
}

export interface PaymentStatusView {
  paymentId: string;
  status: PaymentStatus;
  /** True only when the backend verified settlement (gateway + chain). The only signal that means "paid". */
  settledAndVerified: boolean;
  hsp: HspProgress | null;
  throttled: boolean;
  note: string | null;
}

export interface PaymentReview {
  payerWallet: string | null;
  providerName: string | null;
  providerAgentId: string | null;
  /** Null in demo mode: demo agents have no payout wallet. */
  recipient: string | null;
  amount: string;
  asset: string;
  chainId: number;
  expiresAt: string;
  snapshotHash: string | null;
}

export interface SigningData {
  mode: string;
  /** Validated https URL of the HSP hosted checkout, where the wallet signs. */
  paymentUrl: string;
  cartMandateId: string | null;
  paymentRequestId: string | null;
  expiresAt: string | null;
  tokenAddress: string | null;
  authorizationScheme: string | null;
  recipient: string;
  amount: string;
  asset: string;
  chainId: number;
  instructions: string[];
}

export interface MandateInfo {
  paymentId: string;
  cartMandateId: string | null;
  paymentRequestId: string | null;
  paymentUrl: string | null;
  cartExpiry: string | null;
  orderState: string;
}

export interface Receipt {
  id: string;
  paymentId: string;
  reference: string;
  txHash: string | null;
  settlementStatus: string;
  chainId: number | null;
  tokenAddress: string | null;
  payerAddress: string | null;
  recipient: string | null;
  verifiedAmount: string | null;
  blockNumber: number | null;
  verifiedAt: string | null;
  createdAt: string;
  /** Verification checks as stored by the backend (shown, never recomputed). */
  checks: { name: string; ok: boolean; detail?: string }[];
  source: DataOrigin;
}

export interface PaymentEvent {
  id: string;
  paymentId: string | null;
  type: string;
  data: Record<string, unknown>;
  at: string;
}

export type GuardianState = "passed" | "warning" | "blocked" | "not_evaluated";

export interface GuardianCheck {
  id: string;
  label: string;
  state: GuardianState;
  detail: string;
}

export interface RuleFailure { rule: string; message: string }

export interface GuardianResult {
  /** False until the backend has been asked (no intent yet). */
  evaluated: boolean;
  valid: boolean;
  failures: RuleFailure[];
  hspConfigured: boolean | null;
  source: DataOrigin;
}

export interface SpendingPolicy {
  id: string;
  maxTransactionAmount: string;
  dailySpendingLimit: string;
  allowAllAgents: boolean;
  permittedAgentIds: string[];
  allowedAssets: string[];
  allowedChainIds: number[];
  enabled: boolean;
  updatedAt: string;
  source: DataOrigin;
}

export interface PolicyInput {
  maxTransactionAmount: string;
  dailySpendingLimit: string;
  allowAllAgents: boolean;
  permittedAgentIds: string[];
  allowedAssets: string[];
  allowedChainIds: number[];
  enabled: boolean;
}

export interface PaymentDetail {
  payment: PaymentRecord;
  status: PaymentStatusView | null;
  receipt: Receipt | null;
  events: PaymentEvent[];
  review: PaymentReview | null;
}

export interface PaymentList {
  items: PaymentRecord[];
  total: number;
  /** True when the backend holds more records than were fetched (client-side search/sort only sees the fetched ones). */
  truncated: boolean;
}

export type { PaymentAsset };
