"""Provider Agent: writes the descriptive part of quotations and (demo) deliverables.

Price, asset and delivery time ALWAYS come from the provider's published Service row.
For DEMO agents the narrative and deliverable are generated by Claude (or a template
fallback) and are explicitly labelled as demonstration content.
"""

from __future__ import annotations

import logging
import uuid
from typing import Any

from app.agents.common import wrap_untrusted
from app.agents.prompts import PROVIDER_SYSTEM
from app.agents.schemas import DeliveryOutput, QuoteNarrative
from app.core.errors import UpstreamError
from app.integrations.anthropic.client import ClaudeClient
from app.models import Agent, ProcurementRequest, Service
from app.utils.common import utcnow

log = logging.getLogger(__name__)


class ProviderAgent:
    def __init__(self, claude: ClaudeClient):
        self.claude = claude

    async def build_quotation_details(
        self, user_id: uuid.UUID, agent: Agent, service: Service, request: ProcurementRequest
    ) -> dict[str, Any]:
        narrative: QuoteNarrative | None = None
        generated_by = "template"
        if self.claude.configured:
            try:
                narrative = await self.claude.run_structured(
                    user_id=user_id,
                    system=PROVIDER_SYSTEM,
                    user_content=(
                        f"You are quoting for provider '{agent.name}' (demo={agent.is_demo}). Published service: "
                        f"'{service.name}'. Write the descriptive part of the quotation.\n"
                        + wrap_untrusted("service_description", service.description, 1500)
                        + "\n"
                        + wrap_untrusted("buyer_request", request.description, 2000)
                    ),
                    output_model=QuoteNarrative,
                    output_description="Descriptive part of the quotation.",
                )
                generated_by = "claude"
            except UpstreamError as exc:
                log.warning("Provider narrative fell back to template: %s", exc.code)
        if narrative is None:
            narrative = QuoteNarrative(
                summary=f"{service.name}: {service.description[:500]}".strip(),
                deliverables=[service.name],
                assumptions=["Scope as described in the published service."],
            )
        return {
            "summary": narrative.summary,
            "deliverables": narrative.deliverables,
            "assumptions": narrative.assumptions,
            "demo": agent.is_demo,
            "generated_by": generated_by,
            "price_source": "published_service",
        }

    async def deliver(self, user_id: uuid.UUID, agent: Agent, request: ProcurementRequest) -> dict[str, Any]:
        """Produce the deliverable. The caller MUST have verified settlement first."""
        out: DeliveryOutput | None = None
        generated_by = "template"
        if self.claude.configured:
            try:
                out = await self.claude.run_structured(
                    user_id=user_id,
                    system=PROVIDER_SYSTEM,
                    user_content=(
                        "Produce the purchased deliverable as short, clearly-labelled DEMONSTRATION content "
                        "(no claims of live data).\n" + wrap_untrusted("buyer_request", request.description, 2000)
                    ),
                    output_model=DeliveryOutput,
                    output_description="The deliverable for the buyer.",
                )
                generated_by = "claude"
            except UpstreamError as exc:
                log.warning("Provider delivery fell back to template: %s", exc.code)
        if out is None:
            out = DeliveryOutput(
                title=f"{agent.name} - demonstration deliverable",
                content_markdown=f"Demonstration output for: {request.description[:500]}",
            )
        return {
            "title": out.title,
            "content_markdown": out.content_markdown,
            "demo_content": agent.is_demo,
            "generated_by": generated_by,
            "delivered_at": utcnow().isoformat(),
        }

    @staticmethod
    def track_delivery(request: ProcurementRequest) -> dict[str, Any]:
        return {
            "request_id": str(request.id),
            "delivery_status": request.delivery_status,
            "delivered_at": request.delivered_at.isoformat() if request.delivered_at else None,
        }
